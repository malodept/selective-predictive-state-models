from __future__ import annotations

from dataclasses import dataclass

import torch
from torch.utils.data import Dataset


@dataclass(frozen=True)
class SyntheticDatasetConfig:
    n_samples: int = 2048
    latent_dim: int = 64
    action_dim: int = 8
    noise_std: float = 0.03
    hard_noise_multiplier: float = 8.0
    unreliable_prob: float = 0.25
    mismatch_prob: float = 0.15
    seed: int = 42


class SyntheticPredictiveStateDataset(Dataset):
    """Synthetic latent transitions for SPSM smoke-testing.

    The dataset deliberately separates two notions that matter for the project:

    1. expected_unreliable: a *pre-observation* label. It is predictable from the
       current state/action because it is triggered by large-action transitions.
       This is what the reliability head should learn and what the selector can
       use before paying for optional compute.

    2. observed_surprise: a *post-observation* label. It is generated by replacing
       the future target with a mismatched future from another sample. This is not
       predictable from the input alone; it should mostly be detected by residual
       prediction error after the future observation is available.

    Clean transition:
        z_future = A z_current + B action + noise
    """

    def __init__(self, config: SyntheticDatasetConfig | dict):
        if isinstance(config, dict):
            config = SyntheticDatasetConfig(**config)
        self.config = config
        g = torch.Generator().manual_seed(config.seed)

        latent_dim = config.latent_dim
        action_dim = config.action_dim

        a = torch.randn(latent_dim, latent_dim, generator=g) / (latent_dim**0.5)
        self.A = 0.75 * torch.eye(latent_dim) + 0.15 * a
        self.B = torch.randn(action_dim, latent_dim, generator=g) / (action_dim**0.5)

        self.z_current = torch.randn(config.n_samples, latent_dim, generator=g)
        self.action = torch.randn(config.n_samples, action_dim, generator=g)

        # Pre-observation unreliability: large controls/context shifts are harder.
        action_norm = torch.linalg.vector_norm(self.action, dim=-1)
        threshold = torch.quantile(action_norm, 1.0 - config.unreliable_prob)
        expected_unreliable = action_norm >= threshold

        base_noise = torch.randn(config.n_samples, latent_dim, generator=g)
        noise_scale = torch.where(
            expected_unreliable,
            torch.full_like(action_norm, config.noise_std * config.hard_noise_multiplier),
            torch.full_like(action_norm, config.noise_std),
        )
        noise = noise_scale[:, None] * base_noise
        clean_future = self.z_current @ self.A.T + self.action @ self.B + noise

        # Post-observation surprise: mismatched target, not inferable before seeing it.
        observed_surprise = torch.rand(config.n_samples, generator=g) < config.mismatch_prob
        perm = torch.randperm(config.n_samples, generator=g)
        corrupted_future = clean_future[perm]
        self.z_future = torch.where(observed_surprise[:, None], corrupted_future, clean_future)

        self.clean_future = clean_future
        self.expected_unreliable = expected_unreliable.float()
        self.observed_surprise = observed_surprise.float()
        # Backward-compatible alias used by older tests/scripts.
        self.is_surprise = self.observed_surprise

    def __len__(self) -> int:
        return self.config.n_samples

    def __getitem__(self, idx: int) -> dict[str, torch.Tensor]:
        return {
            "z_current": self.z_current[idx],
            "action": self.action[idx],
            "z_future": self.z_future[idx],
            "clean_future": self.clean_future[idx],
            "expected_unreliable": self.expected_unreliable[idx],
            "observed_surprise": self.observed_surprise[idx],
            "is_surprise": self.is_surprise[idx],
        }
